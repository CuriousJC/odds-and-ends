def esc(s):
    return html.escape(str(s), quote=True)


def url(rel):
    """Relative path -> attribute-safe URL. Spaces are legal in a src but
    '#' and '%' are not, and asset packs do ship both."""
    return esc(quote(rel, safe="/"))


def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return "%d B" % n if unit == "B" else "%.1f %s" % (n, unit)
        n /= 1024.0


def page(title, body):
    return (MARKER + "<!doctype html><html lang=en><meta charset=utf-8>"
            "<meta name=viewport content='width=device-width,initial-scale=1'>"
            "<title>%s</title><style>%s</style>%s<script>%s</script></html>"
            % (esc(title), CSS, body, COPY_JS))


def render_notes(note):
    if not note:
        return ""
    out = ["<div class=notes>"]
    summary = note.get("summary")
    if summary:
        for para in summary.split("\n\n"):
            out.append("<p>%s</p>" % esc(para))
    highlights = note.get("highlights") or []
    if highlights:
        out.append("<ul>%s</ul>" % "".join("<li>%s</li>" % esc(h) for h in highlights))
    out.append("</div>")
    return "".join(out)


def ensure_preview(asset, pack, out, limit, max_edge=1024):
    """Huge sprite sheets cannot be inlined at full size -- a 2048x8192 PNG is
    ~67 MB decoded, and a page of them will hang the browser. For those only,
    write a downscaled copy next to the pages and point the card at it.

    Returns a path relative to `out`, or None to inline the original.
    """
    if not asset.pixels or asset.pixels <= limit:
        return None
    rel = os.path.join("_previews", pack, asset.rel.replace("/", os.sep))
    rel = os.path.splitext(rel)[0] + ".png"
    dst = os.path.join(out, rel)
    if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(asset.abs):
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        try:
            with Image.open(asset.abs) as im:
                im = im.convert("RGBA")
                im.thumbnail((max_edge, max_edge), Image.LANCZOS)
                im.save(dst)
        except Exception:
            return None
    return rel.replace(os.sep, "/")


def render_pack(pack, root, images, archives, other, note, collapsed, dropped=0,
                out=None, inline_limit=0):
    total_bytes = sum(a.bytes for a in images)
    dims = defaultdict(int)
    for a in images:
        if a.w:
            dims[(a.w, a.h)] += 1
    top = sorted(dims.items(), key=lambda kv: -kv[1])[:4]
    top_dims = ", ".join("%dx%d" % wh for wh, _ in top) or "-"
    folded = sum(len(a.variants) for a in collapsed)

    chips = ["%d assets" % len(collapsed), "%d files" % len(images),
             human(total_bytes), "sizes: " + top_dims]
    if folded:
        chips.append("%d resolution variants folded in" % folded)
    if archives:
        chips.append("%d archives" % len(archives))
    if other:
        chips.append("%d other files" % other)
    if dropped:
        chips.append("%d files excluded" % dropped)

    pack_abs = os.path.join(root, pack)
    body = ["<header><h1>%s</h1>" % esc(pack),
            "<div class=sub><a href='index.html'>&larr; all packs</a> &middot; "
            "<span class=path data-full='%s'>%s</span></div>" % (esc(pack_abs), esc(pack_abs)),
            "<div class=stats>%s</div></header><main>"
            % "".join("<span class=chip>%s</span>" % esc(c) for c in chips),
            render_notes(note)]

    if not images:
        body.append("<p class=empty>No browsable images in this pack.</p>")

    by_group = defaultdict(list)
    for a in collapsed:
        by_group[a.group].append(a)

    for grp in sorted(by_group):
        items = by_group[grp]
        body.append("<h2>%s <span class=sub>(%d)</span></h2><div class=grid>"
                    % (esc(grp), len(items)))
        for a in items:
            src = url("%s/%s" % (pack, a.rel))
            dim = "%dx%d" % (a.w, a.h) if a.w else "?"
            if a.variants:
                widths = sorted({v.w for v in a.variants if v.w} | {a.w or 0}, reverse=True)
                dim += " &middot; also " + "/".join(str(s) for s in widths[1:])
            full = os.path.join(root, pack, a.rel.replace("/", os.sep))
            shown = src
            cls = ""
            if inline_limit and out:
                prev = ensure_preview(a, pack, out, inline_limit)
                if prev:
                    shown = url(prev)
                    dim += " &middot; <b>preview</b>"
            if a.w and max(a.w, a.h) <= PIXEL_MAX:
                cls = " class=px"
            body.append(
                "<div class=card><div class=thumb>"
                "<a href='%s' target=_blank><img%s loading=lazy src='%s' alt=''></a></div>"
                "<div class=fn>%s</div><div class=meta>%s &middot; %s</div>"
                "<div class=path data-full='%s' title='click to copy full path'>%s</div></div>"
                % (src, cls, shown, esc(a.name), dim, esc(human(a.bytes)),
                   esc(full), esc(a.rel)))
        body.append("</div>")

    if archives:
        body.append("<h2>archives (not expanded)</h2><div class=wrap><table>"
                    "<tr><th>file</th><th>size</th></tr>")
        for rel, size in archives:
            full = os.path.join(root, pack, rel.replace("/", os.sep))
            body.append("<tr><td><span class=path data-full='%s'>%s</span></td>"
                        "<td class=num>%s</td></tr>" % (esc(full), esc(rel), esc(human(size))))
        body.append("</table></div>")

    body.append("</main>")
    return page("%s - asset catalog" % pack, "".join(body))


def render_index(root, rows, note):
    body = ["<header><h1>Asset catalog</h1><div class=sub>"
            "<span class=path data-full='%s'>%s</span> &middot; %d packs</div></header><main>"
            % (esc(root), esc(root), len(rows)),
            render_notes(note),
            "<div class=wrap><table><tr><th>pack</th><th>assets</th><th>files</th>"
            "<th>size</th><th>notes</th></tr>"]
    for r in rows:
        link = ("<a href='%s'>%s</a>" % (url(r["page"]), esc(r["pack"]))
                if r["page"] else esc(r["pack"]))
        body.append("<tr><td>%s</td><td class=num>%d</td><td class=num>%d</td>"
                    "<td class=num>%s</td><td class=sub>%s</td></tr>"
                    % (link, r["assets"], r["files"], esc(human(r["bytes"])), esc(r["blurb"])))
    body.append("</table></div></main>")
    return page("Asset catalog", "".join(body))


