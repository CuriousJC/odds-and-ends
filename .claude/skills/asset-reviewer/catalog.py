def main():
    ap = argparse.ArgumentParser(description="Build HTML catalogs for asset packs.")
    ap.add_argument("root", help="directory whose immediate subdirectories are packs")
    ap.add_argument("--out", help="where to write the HTML (default: ROOT)")
    ap.add_argument("--pack", action="append", help="limit to this pack (repeatable)")
    ap.add_argument("--sheets-dir", help="also build contact sheets here, for model review")
    ap.add_argument("--no-collapse", action="store_true",
                    help="do not fold numeric resolution folders into one card")
    ap.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                    help="skip directories matching this glob (repeatable), e.g. "
                         "'*-mainV2' to drop duplicated per-engine project copies")
    ap.add_argument("--prune", action="store_true",
                    help="delete previously generated pages whose pack is gone")
    ap.add_argument("--inline-limit", type=int, default=4_000_000, metavar="PIXELS",
                    help="images larger than this get a downscaled preview in "
                         "_previews/ instead of being inlined at full size "
                         "(default 4000000; 0 disables)")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    out = os.path.abspath(args.out) if args.out else root
    if not os.path.isdir(root):
        sys.exit("not a directory: %s" % root)
    os.makedirs(out, exist_ok=True)

    notes = {}
    npath = os.path.join(out, NOTES_FILE)
    if os.path.exists(npath):
        with open(npath, encoding="utf-8") as fh:
            notes = json.load(fh)
    pack_notes = notes.get("packs", {})

    packs = sorted(d for d in os.listdir(root)
                   if os.path.isdir(os.path.join(root, d))
                   and d not in JUNK_DIRS and not d.startswith("_"))
    if args.pack:
        wanted = set(args.pack)
        packs = [p for p in packs if p in wanted]
        missing = wanted - set(packs)
        if missing:
            sys.exit("no such pack(s): %s" % ", ".join(sorted(missing)))
    if not packs:
        sys.exit("no pack directories found under %s" % root)

    rows = []
    generated = {"index.html"}
    for pack in packs:
        images, archives, other, dropped = scan_pack(os.path.join(root, pack),
                                                     args.exclude)
        collapsed = images if args.no_collapse else collapse_resolution_variants(images)
        note = pack_notes.get(pack)

        pagename = "%s.html" % pack
        generated.add(pagename)
        with open(os.path.join(out, pagename), "w", encoding="utf-8") as fh:
            fh.write(render_pack(pack, root, images, archives, other, note,
                                 collapsed, dropped, out, args.inline_limit))

        rows.append({"pack": pack, "page": pagename, "assets": len(collapsed),
                     "files": len(images), "bytes": sum(a.bytes for a in images),
                     "blurb": (note or {}).get("blurb", "")})

        extra = " / %d archives" % len(archives) if archives else ""
        extra += " / %d excluded" % dropped if dropped else ""
        print("%s: %d assets / %d files%s -> %s"
              % (pack, len(collapsed), len(images), extra, pagename))

        if args.sheets_dir and collapsed:
            paths, legend = build_sheets(pack, collapsed, os.path.abspath(args.sheets_dir))
            for p in paths:
                print("    sheet: %s" % p)
            for n, rel, dim in legend:
                print("    [%d] %s (%s)" % (n, rel, dim))

    with open(os.path.join(out, "index.html"), "w", encoding="utf-8") as fh:
        fh.write(render_index(root, rows, notes.get("index")))

    # pages whose pack directory has since been deleted. Only ever touch files
    # carrying our own marker, so a hand-written .html in ROOT is never at risk.
    stale = []
    for fn in sorted(os.listdir(out)):
        if not fn.endswith(".html") or fn in generated:
            continue
        p = os.path.join(out, fn)
        try:
            with open(p, encoding="utf-8") as fh:
                if not fh.read(len(MARKER)).startswith(MARKER):
                    continue
        except OSError:
            continue
        stale.append(fn)
        if args.prune:
            os.remove(p)
    if stale:
        verb = "removed stale page" if args.prune else "stale page (use --prune)"
        for fn in stale:
            print("%s: %s" % (verb, fn))

    print("\nindex -> %s" % os.path.join(out, "index.html"))
    if not os.path.exists(npath):
        print("notes  -> write %s to bake prose into these pages" % npath)


if __name__ == "__main__":
    main()
