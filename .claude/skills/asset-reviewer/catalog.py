#!/usr/bin/env python3
"""Generate browsable HTML catalogs for a directory of game-asset packs.

Each immediate subdirectory of ROOT is treated as one "pack" and gets its own
page; an index.html links them all. Pages reference the original image files by
relative path, so they are only useful sitting in ROOT -- that is deliberate.

Prose written into _catalog_notes.json (next to the pages) is baked into the
generated HTML and survives regeneration.
"""

import argparse
import fnmatch
import html
import json
import os
import sys
from collections import defaultdict
from urllib.parse import quote

try:
    from PIL import Image, ImageDraw
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")

IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".bmp", ".webp"}
ARCHIVE_EXT = {".zip", ".7z", ".rar", ".unitypackage", ".tar", ".gz"}
JUNK_DIRS = {"__MACOSX", ".git", ".svn"}
JUNK_FILES = {".DS_Store", "Thumbs.db", "desktop.ini"}
NOTES_FILE = "_catalog_notes.json"
# stamped into every generated page so --prune only ever removes our own output
MARKER = "<!-- generated by asset-reviewer -->"
# sprites at or under this on their long edge are upscaled with nearest-neighbour
# rather than shown at native size. 64 keeps true pixel art in and 128px icons out.
PIXEL_MAX = 64


# --------------------------------------------------------------------------
# scanning
# --------------------------------------------------------------------------

class Asset:
    __slots__ = ("rel", "abs", "bytes", "w", "h", "variants")

    def __init__(self, rel, abs_, bytes_, w, h):
        self.rel = rel
        self.abs = abs_
        self.bytes = bytes_
        self.w = w
        self.h = h
        self.variants = []   # other Assets collapsed into this one

    @property
    def name(self):
        return os.path.basename(self.rel)

    @property
    def group(self):
        d = os.path.dirname(self.rel)
        return d if d else "(root)"

    @property
    def pixels(self):
        return (self.w or 0) * (self.h or 0)


def scan_pack(pack_dir, exclude=()):
    """Walk one pack. Returns (images, archives, other_count, excluded_count).

    `exclude` holds fnmatch patterns tested against each directory's path
    relative to the pack -- useful for pruning duplicated engine projects.
    """
    images, archives, other, dropped = [], [], 0, 0
    for root, dirs, files in os.walk(pack_dir):
        keep = []
        for d in sorted(dirs):
            if d in JUNK_DIRS:
                continue
            drel = os.path.relpath(os.path.join(root, d), pack_dir).replace("\\", "/")
            if any(fnmatch.fnmatch(drel, p) or fnmatch.fnmatch(d, p) for p in exclude):
                dropped += sum(len(fs) for _, _, fs in os.walk(os.path.join(root, d)))
                continue
            keep.append(d)
        dirs[:] = keep
        for fn in sorted(files):
            if fn in JUNK_FILES or fn.startswith("._"):
                continue
            path = os.path.join(root, fn)
            rel = os.path.relpath(path, pack_dir).replace("\\", "/")
            ext = os.path.splitext(fn)[1].lower()
            if ext in IMAGE_EXT:
                try:
                    with Image.open(path) as im:
                        w, h = im.size
                except Exception:
                    w = h = None
                images.append(Asset(rel, path, os.path.getsize(path), w, h))
            elif ext in ARCHIVE_EXT:
                archives.append((rel, os.path.getsize(path)))
            else:
                other += 1
    return images, archives, other, dropped


def collapse_resolution_variants(images):
    """Fold `.../128/foo.png` and `.../512/foo.png` into one card.

    Keys on the relative path with any purely-numeric directory component
    removed, so resolution folders merge but sibling style folders
    (Round/ vs Square/) stay distinct. Largest pixel count wins as primary.
    """
    buckets = defaultdict(list)
    for a in images:
        parts = [p for p in a.rel.split("/") if not p.isdigit()]
        buckets["/".join(parts)].append(a)

    primaries = []
    for group in buckets.values():
        group.sort(key=lambda a: a.pixels, reverse=True)
        primary = group[0]
        primary.variants = group[1:]
        primaries.append(primary)
    primaries.sort(key=lambda a: a.rel)
    return primaries


# --------------------------------------------------------------------------
# contact sheets (for model review, not for the pages)
# --------------------------------------------------------------------------

def build_sheets(pack_name, assets, out_dir, tile=128, cols=8, rows=8):
    """Tile a representative sample into 1024x1024 PNGs. Returns (paths, legend)."""
    per_sheet = cols * rows
    if not assets:
        return [], []

    # spread the sample evenly across the pack rather than taking a prefix
    cap = per_sheet * 4
    if len(assets) > cap:
        step = len(assets) / cap
        sample = [assets[int(i * step)] for i in range(cap)]
    else:
        sample = list(assets)

    os.makedirs(out_dir, exist_ok=True)
    paths, legend = [], []
    for s_idx in range(0, len(sample), per_sheet):
        chunk = sample[s_idx:s_idx + per_sheet]
        sheet = Image.new("RGB", (cols * tile, rows * tile), (107, 107, 107))
        draw = ImageDraw.Draw(sheet)
        for i, a in enumerate(chunk):
            n = s_idx + i + 1
            legend.append((n, a.rel, "%sx%s" % (a.w, a.h)))
            x, y = (i % cols) * tile, (i // cols) * tile
            try:
                with Image.open(a.abs) as im:
                    im = im.convert("RGBA")
                    im.thumbnail((tile - 12, tile - 12), Image.LANCZOS)
                    sheet.paste(im, (x + (tile - im.width) // 2,
                                     y + (tile - im.height) // 2), im)
            except Exception:
                draw.text((x + 6, y + tile // 2), "err", fill=(255, 80, 80))
            draw.rectangle([x, y, x + tile - 1, y + tile - 1], outline=(60, 60, 60))
            draw.text((x + 3, y + 2), str(n), fill=(255, 255, 0))
        p = os.path.join(out_dir, "%s_sheet%d.png" % (pack_name, s_idx // per_sheet + 1))
        sheet.save(p)
        paths.append(p)
    return paths, legend


