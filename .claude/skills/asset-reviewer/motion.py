def build(sprite_abs, out_dir, back=None):
    with Image.open(sprite_abs) as im:
        w, h = im.size
        bbox = im.convert("RGBA").getbbox()
    rel = os.path.relpath(sprite_abs, out_dir).replace(os.sep, "/")
    name = os.path.basename(sprite_abs)

    head = ["<header><h1>Sprite motion &mdash; ", esc(name), "</h1>"]
    if back:
        head.append("<div class=sub><a href='%s'>&larr; back to the catalog "
                    "index</a></div>" % url(back))
    head.append("</header><main class=usage style='--w:%d'>" % w)

    return (MARKER + "<!doctype html><html lang=en><meta charset=utf-8>"
            "<meta name=viewport content='width=device-width,initial-scale=1'>"
            "<title>Sprite motion &mdash; " + esc(name) + "</title>"
            "<style>" + PAGE_CHROME + SECTION_CSS + demo_css() + "</style><body>"
            + "".join(head)
            + transform_fragment(rel, w, h, bbox)
            + "</main><script>" + section_js() + COPY_JS + "</script></html>")


def main():
    ap = argparse.ArgumentParser(
        description="Demo page showing a static sprite animated by transforms only.")
    ap.add_argument("sprite", help="path to one PNG")
    ap.add_argument("--out", help="directory to write %s into "
                                  "(default: the sprite's directory)" % PAGE_NAME)
    ap.add_argument("--index", default="index.html", metavar="PAGE",
                    help="catalog page to link back to, relative to --out "
                         "(default index.html; '' for no link)")
    args = ap.parse_args()

    sprite = os.path.abspath(args.sprite)
    if not os.path.isfile(sprite):
        sys.exit("no such file: %s" % sprite)
    out = os.path.abspath(args.out) if args.out else os.path.dirname(sprite)
    os.makedirs(out, exist_ok=True)

    # linked unconditionally rather than only when the file is already there --
    # an existence check would make the generated page depend on which order
    # this and catalog.py happened to run in
    back = args.index or None

    with Image.open(sprite) as im:
        sw, sh = im.size
    if max(sw, sh) > 512:
        print("note: %dx%d is large for this page -- it demonstrates how a small "
              "single-frame sprite is animated, and a sheet or full-size artwork "
              "will just be letterboxed." % (sw, sh), file=sys.stderr)

    dst = os.path.join(out, PAGE_NAME)
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(build(sprite, out, back))
    print("motion demo -> %s" % dst)


if __name__ == "__main__":
    main()
