def pick_sprite(items, max_edge=DEMO_MAX_EDGE, sample=48):
    """Choose a representative sprite for the transform demo.

    `items` is an iterable of (abs_path, w, h). Small art only -- a sprite sheet
    or a full-size illustration is not what this demonstrates.

    Returns a path, or None if the pack has no suitable art.
    """
    cand = [(p, w, h) for p, w, h in items
            if w and h and max(w, h) <= max_edge]
    if not cand:
        return None

    # Prefer the pack's uniform canvas. Vendors often ship a tight-cropped
    # "min size" copy alongside a padded one; the padded copy is the canonical
    # presentation, and scoring on content alone would always pick the crop.
    modal = Counter((w, h) for _, w, h in cand).most_common(1)[0][0]
    cand = [c for c in cand if (c[1], c[2]) == modal] or cand
    cand.sort(key=lambda t: t[0])

    # cap the work -- scoring every sprite in a 400-file pack is pointless
    if len(cand) > sample:
        step = len(cand) / float(sample)
        cand = [cand[int(i * step)] for i in range(sample)]

    # most actual artwork wins: a sprite that is mostly padding demos nothing
    best, best_score = None, -1
    for path, w, h in cand:
        try:
            with Image.open(path) as im:
                hist = im.convert("RGBA").getchannel("A").histogram()
                score = sum(hist[129:])
        except Exception:
            continue
        if score > best_score:
            best, best_score = path, score
    return best


def fit_scale(h, target, cap=14):
    """Integer scale that brings a sprite of height h to roughly `target` px.
    Big sprites stay at 1x -- upscaling a 512px icon helps nobody."""
    return max(1, min(cap, round(target / float(h)))) if h else 1


def card(d, scale_var):
    """One animation panel: the sprite running it, plus the CSS that runs it.

    Looping animations are applied at render time. One-shots are not -- a death
    animation ending at opacity 0 would just look like a missing image on load.
    """
    btn = ("<button data-play='%s'>play</button>" % esc(d["id"])
           if d.get("trigger") else "")
    cls = "" if d["id"] == "static" or d.get("trigger") else " a-" + d["id"]
    hold = " data-trigger=1" if d.get("trigger") else ""
    src = ("<pre>%s</pre>" % esc(d["css"])) if d["css"] else \
          "<pre>/* no animation -- the file as shipped */</pre>"
    return ("<div class=ucard style='--cardscale:%s'>"
            "<div class=hd><b>%s</b>%s</div>"
            "<div class=term>%s</div>"
            "<div class=stage><img class='sprite%s' data-anim='%s'%s "
            "src='SPRITE_SRC' alt=''></div>"
            "<p class=why>%s</p>%s</div>"
            % (scale_var, esc(d["label"]), btn, esc(d.get("term", "")),
               cls, esc(d["id"]), hold, esc(d["note"]), src))


def transform_fragment(rel, w, h, bbox=None):
    """The single-pose demo, as HTML to drop inside a `.usage` container.

    `rel` is the sprite's path relative to the page that will hold it.
    """
    src = url(rel)
    card_scale = fit_scale(h, 120)
    hero_scale = fit_scale(h, 190)

    content_note = ""
    if bbox:
        cw, ch = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if (cw, ch) != (w, h):
            content_note = (" &middot; artwork occupies %d&times;%d of that canvas"
                            % (cw, ch))

    body = [
        "<h2>how a single frame moves</h2>",
        "<div class=notes><p>A pack with one pose per creature is not missing "
        "its animation &mdash; it has a different animation budget. Everything "
        "below moves the sprite without redrawing it: CSS transforms, a filter, "
        "and opacity. A game engine does exactly the same thing with the same "
        "maths, which is why an icon set can populate a battle screen.</p>"
        "<p>Every panel is <b>",
        esc(os.path.basename(rel)), "</b> &mdash; %d&times;%d source pixels%s "
        "&mdash; unmodified. The CSS under each panel is the CSS running in it."
        "</p><p><span class=path data-full='%s'>%s</span></p></div>"
        % (w, h, content_note, esc(rel), esc(rel)),

        "<div class=controls>"
        "<label>scale <input type=range id=sc min=1 max=14 step=.25 value=%d>"
        "<span class=val id=scval>%dx</span></label>"
        "<label><input type=checkbox id=snap checked> integer scale only</label>"
        "<label><input type=checkbox id=sm> smooth filtering</label>"
        "</div>" % (hero_scale, hero_scale),

        "<p class=warn id=nonint hidden>&#9888; Non-integer scale: some source "
        "pixels are now wider than their neighbours. In motion this shimmers, "
        "which is why pixel-art games scale the whole framebuffer by a whole "
        "number instead of scaling sprites freely.</p>",
        "<p class=warn>Turn on smooth filtering to see the other half of it. "
        "That is bilinear &mdash; the browser default, and Unity's default "
        "import setting. Pixel-art packs commonly ship "
        "<code>filterMode: 0</code> (Point) precisely to avoid it.</p>",

        "<div class=side><div class=ucard style='--cardscale:var(--scale)'>"
        "<div class=hd><b>live</b></div>"
        "<div class=stage style='height:260px'>"
        "<img class=sprite src='SPRITE_SRC' alt=''></div></div>"
        "<div class=ucard style='--cardscale:1'>"
        "<div class=hd><b>1:1, actual size</b></div>"
        "<div class=stage style='height:260px'>"
        "<img class=sprite src='SPRITE_SRC' alt=''></div>"
        "<p class=why>What the file really is. At 1080p this is about 3% of "
        "screen height.</p></div></div>",

        "<h3 class=sub style='margin:26px 0 6px'>motion from transforms alone"
        "</h3>",
        "<div class=notes><p>The line under each title is the term other people "
        "use. Some are genuinely standard &mdash; <b>squash and stretch</b>, "
        "<b>anticipation</b> and <b>follow-through</b> are three of the twelve "
        "principles of animation, and <b>hitstun</b>, <b>knockback</b>, "
        "<b>easing</b> and <b>tweening</b> are all real terms of art. Others, "
        "like &ldquo;bob&rdquo; and &ldquo;fake walk&rdquo;, are just "
        "descriptions; there is no accepted name for them.</p>"
        "<p>The umbrella terms worth searching are <b>procedural animation</b> "
        "(moving art you did not redraw) and <b>game feel</b> or <b>juice</b> "
        "(the whole business of making input and impact feel physical). Steve "
        "Swink's <i>Game Feel</i> and Jan Willem Nijman's <i>The Art of "
        "Screenshake</i> are the usual starting points.</p></div>",
        "<div class=ugrid>",
    ]
    for d in DEMOS:
        body.append(card(d, card_scale))
    body.append("</div>")

    body.append(
        "<h3 class=sub style='margin:26px 0 6px'>assembled</h3>"
        "<div class=ucard style='--cardscale:" + str(fit_scale(h, 150)) +
        ";max-width:420px'>"
        "<div class=hd><b>combat loop &mdash; <span id=looplbl "
        "style='color:var(--accent)'>stopped</span></b>"
        "<button id=loopbtn>start</button></div>"
        "<div class=stage style='height:230px'>"
        "<img class=sprite id=loopsprite src='SPRITE_SRC' alt=''></div>"
        "<p class=why>idle &rarr; lunge &rarr; idle &rarr; take a hit &rarr; "
        "idle. Four states, one image, no frame budget at all.</p></div>")

    body.append(
        "<div class=notes style='margin-top:22px'><p><b>Where you have seen "
        "this.</b> It is the JRPG battle screen. In the NES-era Final Fantasy "
        "games the enemies are single static images &mdash; the whole attack "
        "readout is the party member stepping forward, the enemy flashing, and "
        "a damage number. The hit flash is the oldest piece here and survived "
        "because it was nearly free: on that hardware it was a palette swap "
        "rather than a filter. The idle bob is <i>not</i> the old part; those "
        "enemies sit perfectly still, and constant subtle motion is a later "
        "mobile and idle-game habit. It is common again now for a different "
        "reason &mdash; it lets a small team ship ninety-six enemies instead "
        "of twelve. Slay the Spire is the usual modern example.</p>"
        "<p><b>What it does not get you.</b> Transform animation cannot change "
        "silhouette. A creature that should open its wings, swing a weapon it "
        "is holding, or turn to face another direction needs real frames. It "
        "also has to be a whole-project decision: a hand-animated player "
        "character next to a bobbing static monster reads as unfinished.</p>"
        "</div>")

    return "".join(body).replace("SPRITE_SRC", src)


