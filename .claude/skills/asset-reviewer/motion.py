FRAME_RE = re.compile(r"^(.*?)[ _-]*(\d{2,})$")


def find_sequences(items, min_frames=3, max_pixels=2_000_000, dir_share=0.6):
    """Spot folders of numbered animation frames.

    `items` is an iterable of (rel_path, width, height). Returns a list of
    dicts sorted by path, each {dir, name, frames, w, h}.

    Numbered filenames are ambiguous -- vendors use them for frames, for tiers,
    and for entirely separate assets -- so three rules have to agree:

    * **Starts at 0 or 1, contiguous.** `jungle_201.png`..`jungle_212.png` are
      twelve different monsters, not a twelve-frame animation.
    * **Small enough to play.** Thirty 2048x8192 sheets numbered 01..30 are a
      monster roster; they also could not be animated in a browser if they were.
    * **Dominates its directory.** `Stat_Attack_01..03` sitting among eighty
      other icons are upgrade tiers. Frames of an animation are what their
      folder is *for*, so the sequences in a directory have to account for most
      of the images in it -- measured collectively, since one folder may
      legitimately hold a walk cycle and an idle cycle side by side.
    """
    per_dir = Counter(posixpath.dirname(rel) for rel, w, h in items if w)
    groups = defaultdict(list)
    for rel, w, h in items:
        if not w or w * h > max_pixels:
            continue
        stem = posixpath.splitext(posixpath.basename(rel))[0]
        m = FRAME_RE.match(stem)
        if not m:
            continue
        base, num = m.group(1), int(m.group(2))
        if not base:
            base = posixpath.basename(posixpath.dirname(rel)) or "frames"
        groups[(posixpath.dirname(rel), base, w, h)].append((num, rel))

    cand = []
    for (d, base, w, h), frames in groups.items():
        if len(frames) < min_frames:
            continue
        frames.sort()
        nums = [n for n, _ in frames]
        if nums[0] > 1 or nums != list(range(nums[0], nums[0] + len(nums))):
            continue
        cand.append({"dir": d, "name": base, "w": w, "h": h,
                     "frames": [r for _, r in frames]})

    covered = Counter()
    for s in cand:
        covered[s["dir"]] += len(s["frames"])
    seqs = [s for s in cand
            if covered[s["dir"]] >= dir_share * per_dir[s["dir"]]]
    seqs.sort(key=lambda s: (s["dir"], s["name"]))
    return seqs


def sequence_fragment(seqs, max_players=8, fps=12):
    """Players for up to `max_players` sequences, spread across the pack."""
    if not seqs:
        return ""
    shown = seqs
    if len(shown) > max_players:
        step = len(shown) / float(max_players)
        shown = [shown[int(i * step)] for i in range(max_players)]

    out = ["<h2>animations <span class=sub>(%d sequences found, showing %d)"
           "</span></h2>" % (len(seqs), len(shown)),
           "<div class=notes><p>These are real frame sequences &mdash; folders "
           "of numbered PNGs that the catalog would otherwise show as dozens of "
           "near-identical cards. Each player holds every frame in the page and "
           "toggles which one is visible, so playback is instant and the frame "
           "rate is yours to set. Vendors rarely ship a timing file, so the "
           "speed here is a guess: 12 fps is a common hand-animation default, "
           "not a value read from the pack.</p></div>",
           "<div class=ugrid>"]
    for s in shown:
        px = " px" if max(s["w"], s["h"]) <= DEMO_MAX_EDGE else ""
        imgs = "".join("<img class='frame%s' src='%s' alt=''>" % (px, url(r))
                       for r in s["frames"])
        # "Attack" alone is ambiguous when four characters each have one, so
        # prefix the subject folder -- the first component below the pack
        parts = s["dir"].split("/")
        title = ("%s &middot; %s" % (esc(parts[1]), esc(s["name"]))
                 if len(parts) > 1 and parts[1] != s["name"] else esc(s["name"]))
        out.append(
            "<div class='ucard fp'>"
            "<div class=hd><b>%s</b><button data-fp=toggle>pause</button></div>"
            "<div class=term>%d frames &middot; %d&times;%d</div>"
            "<div class=stage>%s</div>"
            "<div class=fpctl><button data-step=1>step</button>"
            "<input type=range class=fps min=1 max=30 value=%d>"
            "<span class='val fpsval'>%d fps</span>"
            "<span>frame <b class=fpnum>1/%d</b></span></div>"
            "<div class=path data-full='%s'>%s</div></div>"
            % (title, len(s["frames"]), s["w"], s["h"], imgs,
               fps, fps, len(s["frames"]),
               esc(s["dir"] or "(root)"), esc(s["dir"] or "(root)")))
    out.append("</div>")
    return "".join(out)


