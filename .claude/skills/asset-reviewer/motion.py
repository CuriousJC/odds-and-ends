def detect_grid(path, min_cell=32, max_cols=16, max_rows=64, gutter=0.004):
    """Find the cell grid of a uniform sprite sheet, or None.

    Sheets are laid out on a regular grid with the art inset inside each cell,
    which leaves a fully transparent seam on every cell boundary. So: take the
    square cell sizes that divide both dimensions, and keep the smallest one
    whose boundary columns *and* rows are empty. Smallest matters -- every
    multiple of the true cell size also has empty boundaries, and the finest
    grid is the real one.

    Only the boundary strips are read, never the whole image, so this stays
    cheap on a 2048x8192 sheet.
    """
    try:
        with Image.open(path) as im:
            w, h = im.size
            alpha = im.convert("RGBA").getchannel("A")
    except Exception:
        return None

    def empty(box):
        """Is this strip effectively transparent?"""
        strip = alpha.crop(box)
        n = (box[2] - box[0]) * (box[3] - box[1])
        return n and sum(strip.histogram()[26:]) <= gutter * n

    cells = sorted(c for c in range(min_cell, min(w, h) + 1)
                   if w % c == 0 and h % c == 0
                   and 2 <= w // c <= max_cols and 2 <= h // c <= max_rows)
    for cell in cells:
        cols, rows = w // cell, h // cell
        if not all(empty((x * cell - 1, 0, x * cell + 1, h))
                   for x in range(1, cols)):
            continue
        if not all(empty((0, y * cell - 1, w, y * cell + 1))
                   for y in range(1, rows)):
            continue
        # positive control: the cells themselves must actually hold art
        mid = cell // 2
        if empty((mid - 8, mid - 8, mid + 8, mid + 8)):
            continue
        return cell, cols, rows
    return None


def ensure_sheet_preview(abs_path, rel, out, cols, rows, target=3072):
    """Downscale a sheet for playback and return (rel_path, display_cell).

    A 2048x8192 sheet is ~67 MB decoded. Playing one as a CSS background at
    full size is the difference between a page that opens and one that doesn't,
    and the player only ever shows one cell at a time anyway.
    """
    with Image.open(abs_path) as im:
        w, h = im.size
        scale = min(1.0, target / float(max(w, h)))
        cell_disp = max(24, int(round((w / cols) * scale)))
        size = (cols * cell_disp, rows * cell_disp)
        dst_rel = posixpath.join("_previews", "_sheets",
                                 posixpath.splitext(rel)[0] + ".png")
        dst = os.path.join(out, dst_rel.replace("/", os.sep))
        if (not os.path.exists(dst)
                or os.path.getmtime(dst) < os.path.getmtime(abs_path)):
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            im.convert("RGBA").resize(size, Image.LANCZOS).save(dst)
    return dst_rel, cell_disp


